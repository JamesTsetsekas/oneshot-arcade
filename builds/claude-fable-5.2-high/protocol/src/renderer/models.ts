const infoCache = new Map<string, ModelInfo>();

/** Appends the named model to a geometry builder and returns its metadata. */
export function buildModel(name: string, g: Geom): ModelInfo {
  const b = MODELS[name] ?? MODELS.tool;
  const info = b(g);
  infoCache.set(name, info);
  return info;
}

export function modelInfo(name: string): ModelInfo {
  let i = infoCache.get(name);
  if (!i) i = buildModel(name, new Geom());
  return i;
}

