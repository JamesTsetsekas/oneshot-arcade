/** Rotates a square char grid 90° clockwise `k` times. */
export function rotateRows(rows: string[], k: number): string[] {
  let g = rows.map((r) => r.split(''));
  for (let n = 0; n < ((k % 4) + 4) % 4; n++) {
    const size = g.length;
    const out: string[][] = Array.from({ length: size }, () => Array(size).fill('#'));
    for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) out[x][size - 1 - y] = g[y][x];
    g = out;
  }
  return g.map((r) => r.join(''));
}
