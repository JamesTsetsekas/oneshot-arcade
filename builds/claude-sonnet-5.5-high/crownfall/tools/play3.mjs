// Stage a lane fight and capture ability VFX with real key presses. HERO env selects the hero; OUT the file prefix.
import { chromium } from 'playwright-core';
import { serve } from './serve.mjs';
import fs from 'node:fs';
const PORT = 5545, PREFIX = '/play/claude-sonnet-5.5-high/crownfall/';
const server = serve(PORT, PREFIX);
const exe = ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find((p) => fs.existsSync(p));
const browser = await chromium.launch({ executablePath: exe, headless: true, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const W = Number(process.env.W ?? 1600), H = Number(process.env.H ?? 900);
const page = await browser.newPage({ viewport: { width: W, height: H } });
const logs = [];
page.on('console', (m) => { if (['error', 'warning'].includes(m.type())) logs.push(`[${m.type()}] ${m.text()}`); });
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}\n${e.stack}`));
await page.goto(`http://127.0.0.1:${PORT}${PREFIX}`);
await page.waitForTimeout(1200);
const hero = process.env.HERO ?? 'Brannoch';
const out = process.env.OUT ?? 'a';
await page.click('text=Play'); await page.waitForTimeout(500);
await page.click(`.d-card:has-text("${hero}")`);
await page.click('text=Lock In');
await page.waitForTimeout(4300);
await page.keyboard.press('Escape');
const run = (ticks) => page.evaluate((n) => { const s = window.__crownfall.match.sim; for (let i = 0; i < n; i++) s.step(); }, ticks);
const cmd = (c) => page.evaluate((c) => { const a = window.__crownfall; a.match.sim.command({ ...c, slot: a.match.sim.playerSlot }); }, c);
// learn the first skills for the player quickly (staging) and level up
await page.evaluate(() => { const s = window.__crownfall.match.sim; const h = s.player; s.giveXp(h, 1500); });
for (const k of ['q', 'w', 'e', 'q', 'w']) await page.keyboard.press(`Control+${k}`);
await page.evaluate(() => { const s = window.__crownfall.match.sim; const h = s.player; s.command({ slot: s.playerSlot, c: 'rank', ab: 3 }); });
await cmd({ c: 'move', x: -34, z: -33 });
await run(30 * 60);
await cmd({ c: 'move', x: -10, z: -36 });
await run(30 * 38);
const info = await page.evaluate(() => { const s = window.__crownfall.match.sim; const p = s.player; const foes = s.units.filter((u) => u.team === 1 && !u.dead && (u.kind === 'minion' || u.kind === 'hero')).map((u) => ({ k: u.kind, d: Math.hypot(u.x - p.x, u.z - p.z).toFixed(1) })).slice(0, 6); return { t: s.time.toFixed(0), p: [p.x.toFixed(0), p.z.toFixed(0)], lvl: p.hero.level, foes }; });
console.log(info);
// aim at the enemy side along the lane and cast
await page.mouse.move(W * 0.72, H * 0.33);
await page.waitForTimeout(250);
const press = async (k, hold = 120) => { await page.keyboard.down(k); await page.waitForTimeout(hold); await page.screenshot({ path: `oneshot/${out}-aim-${k}.png` }); await page.keyboard.up(k); await page.waitForTimeout(80); await page.screenshot({ path: `oneshot/${out}-cast-${k}.png` }); await page.waitForTimeout(350); await page.screenshot({ path: `oneshot/${out}-after-${k}.png` }); };
await press('q');
await run(30 * 3);
await press('w');
await run(30 * 2);
await press('r');
await run(5);
await page.waitForTimeout(300);
await page.screenshot({ path: `oneshot/${out}-final.png` });
console.log(logs.slice(0, 20).join('\n') || 'no console errors');
console.log(await page.evaluate(() => { const r = window.__crownfall.renderer.renderer.info; return { calls: r.render.calls, tris: r.render.triangles, geos: r.memory.geometries, tex: r.memory.textures }; }));
await browser.close(); server.close();
