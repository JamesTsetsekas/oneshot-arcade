import { chromium } from 'playwright-core';
import { serve } from './serve.mjs';
import fs from 'node:fs';
const PORT = 5548, PREFIX = '/play/claude-sonnet-5.5-high/crownfall/';
const server = serve(PORT, PREFIX);
const exe = ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find((p) => fs.existsSync(p));
const browser = await chromium.launch({ executablePath: exe, headless: true, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const scale = Number(process.env.SCALE ?? 150);
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
await page.addInitScript((sc) => localStorage.setItem('crownfall.settings.v1', JSON.stringify({ uiScale: sc, colorblind: true, effects: 'low', quality: 'low' })), scale);
const logs = [];
page.on('console', (m) => { if (['error', 'warning'].includes(m.type())) logs.push(`[${m.type()}] ${m.text()}`); });
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
await page.goto(`http://127.0.0.1:${PORT}${PREFIX}`);
await page.waitForTimeout(1200);
await page.click('text=Play'); await page.waitForTimeout(500);
await page.click('.d-card:has-text("Oru")');
await page.click('text=Lock In');
await page.waitForTimeout(4300);
await page.screenshot({ path: 'oneshot/ui150-shop.png' });
await page.keyboard.press('Escape');
await page.evaluate(() => { const s = window.__crownfall.match.sim; for (let i = 0; i < 30 * 20; i++) s.step(); s.damage(s.heroes[3], s.player, 1e6, 'pure'); for (let i = 0; i < 30; i++) s.step(); });
await page.waitForTimeout(600);
await page.screenshot({ path: 'oneshot/ui150-dead.png' });
console.log(logs.join('\n') || 'no console errors');
await browser.close(); server.close();
