export function heroStatsAt(def: HeroDef, level: number): Stats {
  const s = { ...def.base };
  const l = level - 1;
  for (const k of Object.keys(def.perLevel) as (keyof Stats)[]) s[k] += (def.perLevel[k] ?? 0) * l;
  return s;
}
