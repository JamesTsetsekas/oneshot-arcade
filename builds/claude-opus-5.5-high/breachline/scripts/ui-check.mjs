// Headless UI walkthrough + human input path check against a running server (BASE_URL).
import { chromium } from "playwright-core";
import path from "node:path";
const base = process.env.BASE_URL ?? "http://localhost:5420/";
const out = path.resolve(process.argv[2] ?? "oneshot");
const browser = await chromium.launch({ channel: "msedge", headless: true, args: ["--use-angle=d3d11", "--enable-gpu", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
const shot = (n) => page.screenshot({ path: path.join(out, n) });
await page.goto(base); await page.waitForTimeout(800);
await page.getByText("Loadouts", { exact: true }).click(); await page.waitForTimeout(400); await shot("ui-loadouts.png");
await page.getByText("Show exact stats").click(); await page.waitForTimeout(200); await shot("ui-loadouts-adv.png");
await page.getByText("‹ Back").click();
await page.getByText("Settings", { exact: true }).click(); await page.waitForTimeout(300); await shot("ui-settings.png");
await page.getByText("‹ Back").click();
await page.getByText("Profile", { exact: true }).click(); await page.waitForTimeout(300); await shot("ui-profile.png");
await page.getByText("‹ Back").click();
await page.getByText("Practice").first().click(); await page.waitForTimeout(300); await shot("ui-practice.png");
await page.getByText("Deploy", { exact: true }).click();
await page.waitForFunction(() => !!window.__breachline, null, { timeout: 60000 });
await page.waitForTimeout(1500);
await shot("ui-click-to-deploy.png");
await page.mouse.click(640, 360);
await page.waitForTimeout(500);
const s0 = await page.evaluate(() => window.__breachline.state());
console.log("after click", JSON.stringify(s0));
await page.waitForTimeout(8000); // warmup
await page.keyboard.down("KeyW"); await page.waitForTimeout(1500); await page.keyboard.up("KeyW");
const s1 = await page.evaluate(() => window.__breachline.state());
console.log("after W", JSON.stringify(s1));
await page.mouse.move(700, 360); await page.mouse.down(); await page.waitForTimeout(800); await page.mouse.up();
const s2 = await page.evaluate(() => window.__breachline.state());
console.log("after fire", JSON.stringify(s2));
await page.mouse.down({ button: "right" }); await page.waitForTimeout(400); await shot("ui-ads.png"); await page.mouse.up({ button: "right" });
await page.keyboard.down("Tab"); await page.waitForTimeout(300); await shot("ui-scoreboard.png"); await page.keyboard.up("Tab");
await page.keyboard.press("KeyR"); await page.waitForTimeout(500); await shot("ui-reload.png");
await page.keyboard.press("Escape"); await page.waitForTimeout(500); await shot("ui-pause.png");
const s3 = await page.evaluate(() => window.__breachline.state());
console.log("after esc", JSON.stringify(s3));
console.log("errors", errors.join("\n"));
await browser.close();
