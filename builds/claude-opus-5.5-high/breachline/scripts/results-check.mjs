import { chromium } from "playwright-core";
import path from "node:path";
const base = process.env.BASE_URL ?? "http://localhost:5420/";
const out = path.resolve(process.argv[2] ?? "oneshot");
const browser = await chromium.launch({ channel: "msedge", headless: true, args: ["--use-angle=d3d11", "--enable-gpu", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = []; page.on("pageerror", (e) => errors.push(e.message));
await page.goto(`${base}?autostart=1&demo=1&warmup=2&score=6`);
await page.waitForSelector(".results", { timeout: 120000 });
await page.waitForTimeout(800);
await page.screenshot({ path: path.join(out, "results.png") });
await page.mouse.wheel(0, 600); await page.waitForTimeout(300);
await page.screenshot({ path: path.join(out, "results-2.png") });
const prof = await page.evaluate(() => JSON.parse(localStorage.getItem("breachline.profile")));
console.log("xp", prof.xp, "matches", prof.stats.matches, "processed", prof.processed);
await page.getByText("Play again").click();
await page.waitForFunction(() => !!window.__breachline, null, { timeout: 60000 });
console.log("requeued", await page.evaluate(() => JSON.stringify(window.__breachline.state())));
console.log("errors", errors.join("\n"));
await browser.close();
